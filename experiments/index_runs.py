"""
Keep the measured results in git, and an index of them, so a finding can be looked up
instead of re-run.

Copies every run's small outputs (config, metrics, gates, stream and experiment JSON, eval
and training logs; never checkpoints) from runs/ into results/<run>/, then writes
results/INDEX.md: one row per run with its training settings, the wrong-reference control,
and headline numbers from its most complete stream evaluation. Safe to re-run at any time.

Usage: python -m experiments.index_runs
"""
from __future__ import annotations

import json
import shutil
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS, RESULTS = ROOT / "runs", ROOT / "results"
# Most complete protocol first: which stream file a run's headline numbers come from.
STREAMS = [
    ("stream_v3_reftime.json", "v3, stride 2, 3 unseen tracks"),
    ("stream_v3.json", "v3, stride 2, 3 unseen tracks"),
    ("stream_lag_23_stride2.json", "v2, stride 2, Silverstone 46 pairs"),
    ("stream_lag_23.json", "v2, stride 4, Silverstone 46 pairs"),
    ("stream_speed_seed0.json", "v2, stride 4, Silverstone 6 pairs"),
    ("stream_seed0.json", "v2, stride 4, Silverstone 6 pairs"),
]
DEFAULTS = {"strides": "1,2,3,4", "target_at": "last", "mirror_p": 0.0, "width": 32, "hidden": 64,
            "lr": 3e-4, "clip_len": 12, "reference_axis": "time"}


def sync() -> list[str]:
    runs = sorted(p.name for p in RUNS.iterdir() if (p / "config.json").exists())
    for name in runs:
        out = RESULTS / name
        out.mkdir(parents=True, exist_ok=True)
        for f in list((RUNS / name).glob("*.json")) + list((RUNS / name).glob("*.log")):
            shutil.copy2(f, out / f.name)
        for log in (RUNS / "lc_logs").glob(f"{name}.*log"):
            shutil.copy2(log, out / log.name)
    other = RESULTS / "_other"
    for f in list((RUNS / "lc_logs").glob("*")) + [RUNS / "v3"]:
        stem = f.name.split(".")[0]
        if f.is_file() and stem not in runs:
            other.mkdir(exist_ok=True)
            shutil.copy2(f, other / f.name)
        elif f.is_dir():
            for g in f.glob("*.json"):
                other.mkdir(exist_ok=True)
                shutil.copy2(g, other / f"{f.name}_{g.name}")
    return runs


def training(args: dict) -> str:
    parts = []
    if args.get("camera_aug"):
        parts.append(f"aug[{args.get('aug_parts', 'all')}] pitch±{args.get('aug_pitch', 3)}")
    for key, default in DEFAULTS.items():
        value = args.get(key, default)
        if value is not None and value != default:
            parts.append(f"{key}={value}")
    if args.get("with_look"):
        parts.append("with_look")
    if args.get("corr_degrade"):
        parts.append(f"corr_degrade={args['corr_degrade']}")
    if args.get("ref_grad_random") is not None:
        parts.append(f"ref_grad_random={args['ref_grad_random']}")
    if args.get("tracks"):
        parts.append(f"{len(str(args['tracks']).split(','))} tracks")
    if args.get("init"):
        parts.append(f"init {Path(args['init']).parent.name}")
    parts.append(f"{args.get('steps')} steps")
    return ", ".join(parts)


def pct(report: dict, key: str) -> str:
    row = report.get(key)
    return f"{100 * row['over_100ms']:.1f}%" if row else ""


def row(name: str) -> str:
    folder = RESULTS / name
    args = json.loads((folder / "config.json").read_text()).get("args", {})
    checkpoint = RUNS / name / "best.pt"
    when = datetime.fromtimestamp(checkpoint.stat().st_mtime).strftime("%Y-%m-%d %H:%M") if checkpoint.exists() else ""
    control = ""
    for gates in ("gates_v3.json", "gates.json"):
        if (folder / gates).exists():
            control = json.loads((folder / gates).read_text()).get("controls", {}).get("wrong_reference", {}).get("verdict", "")
            break
    head = ["", "", "", "", ""]
    for file, label in STREAMS:
        if (folder / file).exists():
            report = json.loads((folder / file).read_text())["report"]
            head = [label, pct(report, "G1 filter"), pct(report, "G2 filter"),
                    pct(report, "G2 filter, reference time"), pct(report, "G2 filter + speed")]
            break
    files = ", ".join(sorted(f.name for f in folder.glob("*.json") if f.name not in ("config.json", "metrics.json")))
    data = Path(str(args.get("data", ""))).name
    return (f"| {name} | {when} | {data} | {training(args)} | {args.get('seed', '')} | {control} | "
            + " | ".join(head) + f" | {files} |")


def main() -> None:
    runs = sync()
    rows = sorted((row(n) for n in runs), key=lambda r: r.split(" | ")[1], reverse=True)
    header = [
        "# Results index",
        "",
        "Generated by `python -m experiments.index_runs` from `runs/` (checkpoints stay there, on",
        "the Mac). One row per training run, newest first. The four percentages are the share of",
        "15 Hz ticks more than 100 ms off, from the run's most complete stream evaluation",
        "(named in *protocol*): G1 = held-out laps of trained tracks with the filter in metres; G2 =",
        "unseen tracks with the filter in metres, in reference time, and with true speed. Empty",
        "means not measured under that protocol. Every result file is next to this index, in the",
        "run's folder; what each experiment tested is in `experiments/README.md` and",
        "`docs/ml-pivot.md`.",
        "",
        "| run | finished | data | training | seed | wrong-ref control | protocol | G1 | G2 metres | G2 ref. time | G2 + speed | other results |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    (RESULTS / "INDEX.md").write_text("\n".join(header + rows) + "\n")
    print(f"{len(runs)} runs indexed in {RESULTS / 'INDEX.md'}")


if __name__ == "__main__":
    main()
